const STRENGTH_KEY = { '清淡': 'strength_light', '中等': 'strength_medium', '浓郁': 'strength_full' };

function getLang() { return localStorage.getItem(LANG_KEY) || 'zh'; }
function setLang(lang) { localStorage.setItem(LANG_KEY, lang); location.reload(); }

function t(key) {
  const lang = getLang();
  return (TRANSLATIONS[lang] ?? TRANSLATIONS.zh)[key] ?? TRANSLATIONS.zh[key] ?? key;
}
function tFn(key, ...args) {
  const lang = getLang();
  const fn = (TRANSLATIONS[lang] ?? TRANSLATIONS.zh)[key] ?? TRANSLATIONS.zh[key];
  return typeof fn === 'function' ? fn(...args) : fn;
}
function tStrength(stored) { return t(STRENGTH_KEY[stored] || 'strength_medium'); }

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === getLang());
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
}
